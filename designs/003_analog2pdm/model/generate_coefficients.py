"""Generate reproducible Q2.16 halfband coefficients; --check never rewrites files."""
from pathlib import Path
import argparse
import json
import numpy as np

ROOT = Path(__file__).resolve().parents[1]


def coefficients():
    result = []
    for taps in (95, 31, 15):
        m = np.arange(taps) - (taps - 1) / 2
        h = np.sinc(m / 2) * np.kaiser(taps, 8.6)
        h *= 2 / h.sum()
        q = np.rint(h * 65536).astype(np.int64)
        center = (taps - 1) // 2
        q[1::2] = 0
        q[center] = 65536
        correction = 131072 - int(q.sum())
        assert correction % 2 == 0
        q[center - 1] += correction // 2
        q[center + 1] += correction // 2
        assert int(q.sum()) == 131072
        assert np.array_equal(q, q[::-1])
        result.append(q.tolist())
    return result


def outputs():
    tables = coefficients()
    lines = [
        '// Generated by model/generate_coefficients.py; signed Q2.16.',
        'module halfband_coeff #(parameter integer STAGE = 0) (',
        '    input wire [5:0] index, output reg signed [17:0] coefficient',
        ');', '    always @* begin', '        coefficient = 0;',
        '        case (STAGE)',
    ]
    for stage, q in enumerate(tables):
        lines += [f'            {stage}: case (index)']
        for index, v in enumerate(q[0::2]):
            lines += [f"                6'd{index}: coefficient = {('-' if v < 0 else '')}18'sd{abs(v)};"]
        lines += ['                default: coefficient = 0;', '            endcase']
    lines += ['            default: coefficient = 0;', '        endcase', '    end', 'endmodule', '']
    return {
        ROOT / 'model/coefficients.json': json.dumps(tables, indent=2) + '\n',
        ROOT / 'rtl/halfband_coeff.sv': '\n'.join(lines),
    }


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, text in outputs().items():
        if args.check:
            assert path.read_text(encoding='utf-8') == text, f'Stale coefficients: {path}'
        else:
            path.write_text(text, encoding='utf-8', newline='\n')
    print('TEST coefficients ... PASS')
